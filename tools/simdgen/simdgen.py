def gen_signature(slot: SlotEntry) -> str:
    """Generate the function pointer type signature for a dispatch slot."""
    t = slot.type_info
    sig = slot.op.signature

    if sig == "binary":
        return f"function(const a, b: {t.vec_type}): {t.vec_type}"
    elif sig == "unary":
        return f"function(const a: {t.vec_type}): {t.vec_type}"
    elif sig == "compare":
        return f"function(const a, b: {t.vec_type}): {t.mask_type}"
    elif sig == "reduce":
        return f"function(const a: {t.vec_type}): {t.scalar_type}"
    elif sig == "load":
        return f"function(p: {t.ptr_type}): {t.vec_type}"
    elif sig == "store":
        return f"procedure(p: {t.ptr_type}; const a: {t.vec_type})"
    elif sig == "splat":
        return f"function(value: {t.scalar_type}): {t.vec_type}"
    elif sig == "zero":
        return f"function: {t.vec_type}"
    elif sig == "shift":
        return f"function(const a: {t.vec_type}; count: Integer): {t.vec_type}"
    elif sig == "ternary":
        return f"function(const a, b, c: {t.vec_type}): {t.vec_type}"
    else:
        return f"{{unknown signature: {sig}}}"


def generate_dispatch_slots(registry: Registry) -> str:
    lines = [HEADER, "{ Dispatch table slots }", ""]
    current_category = ""
    for slot in registry.slots:
        if slot.op.category != current_category:
            current_category = slot.op.category
            lines.append(f"    {{ --- {current_category} --- }}")
        sig = gen_signature(slot)
        lines.append(f"    {slot.dispatch_field}: {sig};")
    return "\n".join(lines) + "\n"


