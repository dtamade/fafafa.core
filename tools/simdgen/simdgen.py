"""
simdgen - SIMD dispatch code generator for fafafa.core.simd

Generates Pascal include files from JSON operation definitions.
Zero external dependencies (uses only Python stdlib).

Usage:
    python3 tools/simdgen/simdgen.py [--verify] [--dry-run]

Options:
    --verify   Compare generated output against existing code (audit mode)
    --dry-run  Print what would be generated without writing files
"""

